import type { Intake } from '../types/neuro';
export function recommendations(v: Intake): { title: string; text: string }[] {
  const result = [];
  if (v.sleep !== undefined && v.sleep < 7)
    result.push({
      title: 'Дайте отдыху место в расписании',
      text: 'Вы сообщили о коротком сне. Можно понаблюдать, как более регулярное время отхода ко сну связано с вашим самочувствием.',
    });
  if (v.stress !== undefined && v.stress >= 6)
    result.push({
      title: 'Небольшая пауза между задачами',
      text: 'При ощущении высокой нагрузки попробуйте спокойный перерыв или короткую прогулку. Это общая идея, а не медицинский совет.',
    });
  if (v.focus !== undefined && v.focus <= 5)
    result.push({
      title: 'Одна задача за раз',
      text: 'Попробуйте убрать уведомления на короткий отрезок работы и отметьте, становится ли комфортнее удерживать фокус.',
    });
  if (v.activity === 'low')
    result.push({
      title: 'Движение без соревнования',
      text: 'Если вам удобно, добавьте небольшую прогулку в обычный день. Наблюдайте за ощущениями без цели улучшить баллы.',
    });
  if (!result.length)
    result.push({
      title: 'Замечайте контекст, а не только баллы',
      text: 'При повторном прохождении используйте то же устройство и способ ввода. Отмечайте сон и время дня: условия влияют на задания.',
    });
  return result.slice(0, 2);
}
